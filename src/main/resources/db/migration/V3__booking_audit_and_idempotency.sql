CREATE TABLE booking_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pnr VARCHAR(10) NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    actor_email VARCHAR(255),
    details VARCHAR(1000) NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX idx_booking_audit_pnr_created ON booking_audit_events (pnr, created_at);
CREATE INDEX idx_booking_audit_created ON booking_audit_events (created_at);

CREATE TABLE booking_idempotency_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email VARCHAR(255) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    booking_id BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    CONSTRAINT uk_booking_idempotency_user_key UNIQUE (user_email, idempotency_key),
    CONSTRAINT uk_booking_idempotency_booking UNIQUE (booking_id),
    CONSTRAINT fk_booking_idempotency_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE
);
CREATE INDEX idx_booking_idempotency_created ON booking_idempotency_records (created_at);
