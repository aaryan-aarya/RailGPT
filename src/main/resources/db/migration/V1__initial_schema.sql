-- ===========================================================================
-- RailGPT initial schema (PostgreSQL).
--
-- This migration creates the hardened RailGPT schema. It is a BREAKING change
-- from the original single-passenger backend: bookings now carry a journey
-- date + travel class and a child collection of passengers, and seat inventory
-- is per (train, journey_date, class), derived from passenger rows.
--
-- IMPORTANT:
--   * This migration only CREATEs objects; it never DROPs or ALTERs existing
--     tables, so it will not overwrite an existing database.
--   * On a database that already contains the OLD incompatible schema, Flyway
--     will fail loudly on the first CREATE TABLE. That is intentional: migrate
--     such a database manually (see DECISIONS.md) rather than risk data loss.
--   * For a fresh database this migration fully provisions the schema.
--
-- Column naming follows Hibernate's CamelCaseToUnderscoresNamingStrategy so
-- that spring.jpa.hibernate.ddl-auto=validate succeeds against this schema.
-- ===========================================================================

-- ---- users ---------------------------------------------------------------
CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    password    VARCHAR(255) NOT NULL,
    role        VARCHAR(255) NOT NULL DEFAULT 'USER',
    phone       VARCHAR(255),
    created_at  BIGINT       NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);
CREATE UNIQUE INDEX idx_users_email ON users (email);

-- ---- trains --------------------------------------------------------------
CREATE TABLE trains (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_number     VARCHAR(255) NOT NULL,
    train_name       VARCHAR(255) NOT NULL,
    source           VARCHAR(255) NOT NULL,
    destination      VARCHAR(255) NOT NULL,
    departure_time   VARCHAR(255),
    arrival_time     VARCHAR(255),
    duration_minutes INTEGER,
    distance_km      INTEGER,
    train_type       VARCHAR(255),
    CONSTRAINT uk_trains_number UNIQUE (train_number)
);
CREATE UNIQUE INDEX idx_trains_number ON trains (train_number);
CREATE INDEX idx_trains_route ON trains (source, destination);

-- ---- train_classes (per-class capacity / fare / quota) -------------------
CREATE TABLE train_classes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id      BIGINT       NOT NULL,
    class_type    VARCHAR(255) NOT NULL,
    total_seats   INTEGER      NOT NULL,
    fare          INTEGER      NOT NULL,
    rac_limit     INTEGER      NOT NULL DEFAULT 18,
    waiting_limit INTEGER      NOT NULL DEFAULT 40,
    CONSTRAINT fk_train_classes_train FOREIGN KEY (train_id) REFERENCES trains (id) ON DELETE CASCADE
);
CREATE INDEX idx_train_classes_train ON train_classes (train_id);

-- ---- train_days_of_run (element collection of running days) --------------
CREATE TABLE train_days_of_run (
    train_id   BIGINT       NOT NULL,
    day_of_run VARCHAR(255),
    CONSTRAINT fk_train_days_train FOREIGN KEY (train_id) REFERENCES trains (id) ON DELETE CASCADE
);
CREATE INDEX idx_train_days_train ON train_days_of_run (train_id);

-- ---- bookings (one PNR, per date + class, multi-passenger) ---------------
CREATE TABLE bookings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pnr          VARCHAR(10)  NOT NULL,
    train_number VARCHAR(255) NOT NULL,
    train_name   VARCHAR(255) NOT NULL,
    user_email   VARCHAR(255) NOT NULL,
    journey_date VARCHAR(255) NOT NULL,
    class_type   VARCHAR(255) NOT NULL,
    boarding     VARCHAR(255),
    reservation  VARCHAR(255),
    source       VARCHAR(255) NOT NULL,
    destination  VARCHAR(255) NOT NULL,
    status       VARCHAR(255) NOT NULL,
    total_fare   INTEGER      NOT NULL DEFAULT 0,
    created_at   BIGINT       NOT NULL,
    cancelled_at BIGINT,
    CONSTRAINT uk_bookings_pnr UNIQUE (pnr)
);
CREATE UNIQUE INDEX idx_bookings_pnr ON bookings (pnr);
CREATE INDEX idx_bookings_user ON bookings (user_email);
CREATE INDEX idx_bookings_train_date_class ON bookings (train_number, journey_date, class_type);

-- ---- passengers (per-passenger status / seat / queue position) -----------
CREATE TABLE passengers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id       BIGINT       NOT NULL,
    name             VARCHAR(255) NOT NULL,
    age              INTEGER      NOT NULL,
    gender           VARCHAR(255) NOT NULL,
    berth_preference VARCHAR(255),
    status           VARCHAR(255) NOT NULL,
    seat_number      INTEGER,
    coach_number     VARCHAR(255),
    berth_type       VARCHAR(255),
    rac_number       INTEGER,
    waiting_number   INTEGER,
    CONSTRAINT fk_passengers_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE
);
CREATE INDEX idx_passengers_booking ON passengers (booking_id);
CREATE INDEX idx_passengers_status ON passengers (status);
